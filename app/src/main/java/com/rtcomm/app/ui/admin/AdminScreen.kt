/** List<String> 的 Saver：让刚生成的邀请码/兑换码在进程被回收重建后仍然可见。 */
private val StringListSaver = androidx.compose.runtime.saveable.listSaver<List<String>, String>(
    save = { it },
    restore = { it },
)

/** 等待二次确认的破坏性操作。 */
private data class PendingConfirm(
    val title: String,
    val message: String,
    val confirmText: String,
    val action: () -> Unit,
)

/** 一次刷新拉取的全部管理数据。 */
private data class AdminData(
    val stats: AdminStats,
    val users: List<AdminUser>,
    val invites: com.rtcomm.app.data.InviteCodesResp,
    val conversations: List<com.rtcomm.app.data.AdminConversation>,
)

/**
 * 管理后台：账号总览 + 邀请码管理。
 *
 * 入口在设置页仅对管理员可见，但真正的权限判定在服务端
 * （管理接口全部挂了 adminRequired），这里隐藏只是体验优化。
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AdminScreen(onBack: () -> Unit) {
    val scope = rememberCoroutineScope()
    val clipboard = LocalClipboardManager.current
    val snackbar = remember { SnackbarHostState() }

    var tab by remember { mutableIntStateOf(0) } // 0=账号 1=邀请码 2=会话
    var loading by remember { mutableStateOf(true) }
    var err by remember { mutableStateOf<String?>(null) }
    var stats by remember { mutableStateOf(AdminStats()) }
    var users by remember { mutableStateOf<List<AdminUser>>(emptyList()) }
    var invites by remember { mutableStateOf<List<InviteCode>>(emptyList()) }
    var inviteStats by remember { mutableStateOf(InviteStats()) }
    var typeFilter by remember { mutableStateOf("all") }
    var query by rememberSaveable { mutableStateOf("") }
    var showGenerate by remember { mutableStateOf(false) }
    var generating by remember { mutableStateOf(false) }
    var genCount by remember { mutableStateOf("1") }
    var genNote by remember { mutableStateOf("") }
    var lastGenerated by rememberSaveable(stateSaver = StringListSaver) { mutableStateOf<List<String>>(emptyList()) }
    /** 正在操作的目标账号（弹出管理动作菜单） */
    var userActionTarget by remember { mutableStateOf<AdminUser?>(null) }
    var pwdTarget by remember { mutableStateOf<AdminUser?>(null) }
    var conversations by remember { mutableStateOf<List<com.rtcomm.app.data.AdminConversation>>(emptyList()) }
    var convDetail by remember { mutableStateOf<com.rtcomm.app.data.AdminConversation?>(null) }
    var busyAction by remember { mutableStateOf(false) }
    /** 待确认的破坏性操作（作废邀请码 / 禁用账号 / 踢下线 / 清除 Key / 作废兑换码）。 */
    var confirmAction by remember { mutableStateOf<PendingConfirm?>(null) }

    suspend fun reload() {
        loading = true
        err = null
        val res = withContext(Dispatchers.IO) {
            runCatching {
                val s = Api.adminStats()
                val u = Api.adminUsers(typeFilter, query.ifBlank { null })
                val inv = Api.listInvites()
                val convs = Api.adminConversations()
                AdminData(s, u, inv, convs)
            }
        }
        res.onSuccess { d ->
            stats = d.stats
            users = d.users
            invites = d.invites.codes
            inviteStats = d.invites.stats
            conversations = d.conversations
        }
        res.onFailure { err = Api.userMessage(it) }
        loading = false
    }

    LaunchedEffect(Unit) { reload() }

    Scaffold(
        topBar = {
            AppTopBar(
                title = "管理后台",
                onBack = onBack,
            )
        },
        snackbarHost = { SnackbarHost(snackbar) },
    ) { pad ->
        Column(Modifier.fillMaxSize().padding(pad)) {
            TabRow(selectedTabIndex = tab) {
                Tab(selected = tab == 0, onClick = { tab = 0 }, text = { Text("账号") })
                Tab(selected = tab == 1, onClick = { tab = 1 }, text = { Text("邀请码") })
                Tab(selected = tab == 2, onClick = { tab = 2 }, text = { Text("会话") })
                Tab(selected = tab == 3, onClick = { tab = 3 }, text = { Text("AI 设置") })
                Tab(selected = tab == 4, onClick = { tab = 4 }, text = { Text("额度") })
            }
            err?.let { ErrorBanner(it, onRetry = { scope.launch { reload() } }) }

            // 加载状态用一条细进度线表示：不遮内容、不跳版，切页签/搜索时也能立刻看到反馈。
            Box(Modifier.fillMaxWidth().height(4.dp)) {
                Reveal(loading) {
                    LinearProgressIndicator(
                        modifier = Modifier.fillMaxWidth().height(3.dp),
                    )
                }
            }

            // 页签内容之间淡切，替代整块硬替换。
            // 注意：Crossfade 的内容放在同一个 Box 中，同一分支内多个同级组件会叠放；
            // 「账号」页签必须用 Column 包裹，否则统计行/搜索框/列表会互相遮挡。
            FadeSwap(target = tab, modifier = Modifier.fillMaxSize()) { currentTab ->
            when (currentTab) {
                0 -> Column(Modifier.fillMaxSize()) {
                StatsRow(stats)
                // 类型筛选
                Row(
                    Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()).padding(horizontal = 12.dp),
                    horizontalArrangement = Arrangement.spacedBy(Space.sm),
                ) {
                    listOf("all" to "全部", "human" to "用户", "bot" to "机器人").forEach { (key, label) ->
                        FilterChip(
                            selected = typeFilter == key,
                            onClick = { typeFilter = key; scope.launch { reload() } },
                            label = { Text(label) },
                        )
                    }
                }
                Row(
                    Modifier.fillMaxWidth().padding(horizontal = 12.dp, vertical = 6.dp),
                    verticalAlignment = Alignment.CenterVertically,
                ) {
                    OutlinedTextField(
                        value = query,
                        onValueChange = { query = it },
                        label = { Text("搜索用户名或昵称") },
                        singleLine = true,
                        keyboardOptions = KeyboardOptions(imeAction = ImeAction.Search),
                        keyboardActions = KeyboardActions(onSearch = { scope.launch { reload() } }),
                        trailingIcon = if (query.isNotBlank()) {
                            {
                                IconButton(onClick = { query = ""; scope.launch { reload() } }) {
                                    Icon(Icons.Filled.Close, contentDescription = "清空搜索")
                                }
                            }
                        } else null,
                        modifier = Modifier.weight(1f),
                    )
                    Spacer(Modifier.width(Space.sm))
                    Button(onClick = { scope.launch { reload() } }) { Text("查询") }
                }

                FadeSwap(if (loading && users.isEmpty()) 0 else if (users.isEmpty()) 1 else 2) { st ->
                    when (st) {
                        0 -> LoadingBox()
                        1 -> EmptyState(Icons.Filled.Search, "没有匹配的账号", "换个关键词或筛选条件试试")
                        else -> LazyColumn(Modifier.fillMaxSize()) {
                            items(users, key = { it.id }) { u ->
                                AdminUserRow(u, Modifier.animateItem()) { userActionTarget = u }
                            }
                        }
                    }
                }
            }
                2 -> {
                FadeSwap(if (loading && conversations.isEmpty()) 0 else if (conversations.isEmpty()) 1 else 2) { st ->
                    when (st) {
                        0 -> LoadingBox()
                        1 -> EmptyState(Icons.Filled.Forum, "还没有会话", null)
                        else -> LazyColumn(Modifier.fillMaxSize()) {
                            items(conversations, key = { it.id }) { c ->
                                AdminConversationRow(c, Modifier.animateItem()) { convDetail = c }
                            }
                        }
                    }
                }
            }
                1 -> {
                InviteTab(
                    stats = inviteStats,
                    invites = invites,
                    onGenerate = { showGenerate = true },
                    onCopy = { code ->
                        clipboard.setText(AnnotatedString(code))
                        scope.launch { snackbar.showSnackbar("已复制邀请码") }
                    },
                    onRevoke = { code ->
                        confirmAction = PendingConfirm(
                            title = "作废邀请码",
                            message = "作废后「$code」将无法再被使用，且不可撤销。",
                            confirmText = "作废",
                        ) {
                            scope.launch {
                                val r = withContext(Dispatchers.IO) { runCatching { Api.revokeInvite(code) } }
                                r.onSuccess {
                                    snackbar.showSnackbar("已作废")
                                    reload()
                                }.onFailure { snackbar.showSnackbar(Api.userMessage(it)) }
                            }
                        }
                    },
                )
            }
                3 -> {
                AiSettingsTab(snackbar = snackbar)
            }
                else -> {
                RedeemCodesTab(snackbar = snackbar, clipboard = clipboard)
            }
            }
            }
        }
    }

    // 账号管理动作
    userActionTarget?.let { target ->
        UserActionDialog(
            user = target,
            onDismiss = { userActionTarget = null },
            onToggleDisabled = {
                val enabling = target.isDisabled
                if (enabling) {
                    busyAction = true
                    scope.launch {
                        val r = withContext(Dispatchers.IO) {
                            runCatching { Api.adminSetUserDisabled(target.id, false) }
                        }
                        busyAction = false
                        r.onSuccess {
                            snackbar.showSnackbar("已恢复 ${target.displayName}")
                            userActionTarget = null
                            reload()
                        }.onFailure { snackbar.showSnackbar(Api.userMessage(it)) }
                    }
                } else {
                    userActionTarget = null
                    confirmAction = PendingConfirm(
                        title = "禁用账号",
                        message = "禁用后「${target.displayName}」将无法登录，此操作会立即生效。",
                        confirmText = "禁用",
                    ) {
                        busyAction = true
                        scope.launch {
                            val r = withContext(Dispatchers.IO) {
                                runCatching { Api.adminSetUserDisabled(target.id, true) }
                            }
                            busyAction = false
                            r.onSuccess {
                                snackbar.showSnackbar("已禁用 ${target.displayName}")
                                reload()
                            }.onFailure { snackbar.showSnackbar(Api.userMessage(it)) }
                        }
                    }
                }
            },
            onResetPassword = { pwdTarget = target; userActionTarget = null },
            onKick = {
                userActionTarget = null
                confirmAction = PendingConfirm(
                    title = "踢下线",
                    message = "「${target.displayName}」的当前登录会立即失效，需要重新登录。",
                    confirmText = "踢下线",
                ) {
                    busyAction = true
                    scope.launch {
                        val r = withContext(Dispatchers.IO) { runCatching { Api.adminKickUser(target.id) } }
                        busyAction = false
                        r.onSuccess {
                            snackbar.showSnackbar("已踢下线，该账号需重新登录")
                            reload()
                        }.onFailure { snackbar.showSnackbar(Api.userMessage(it)) }
                    }
                }
            },
        )
    }

    confirmAction?.let { c ->
        ConfirmDialog(
            title = c.title,
            message = c.message,
            confirmText = c.confirmText,
            onConfirm = c.action,
            onDismiss = { confirmAction = null },
        )
    }

    pwdTarget?.let { target ->
        ResetPasswordDialog(
            user = target,
            busy = busyAction,
            onDismiss = { pwdTarget = null },
            onConfirm = { newPwd ->
                busyAction = true
                scope.launch {
                    val r = withContext(Dispatchers.IO) {
                        runCatching { Api.adminResetPassword(target.id, newPwd) }
                    }
                    busyAction = false
                    r.onSuccess {
                        snackbar.showSnackbar("已重置 ${target.displayName} 的密码")
                        pwdTarget = null
                        reload()
                    }.onFailure { snackbar.showSnackbar(Api.userMessage(it)) }
                }
            },
        )
    }

    // 查看会话（只读）
    convDetail?.let { c ->
        ConversationViewerDialog(conversation = c, onDismiss = { convDetail = null })
    }

    if (showGenerate) {
        AppAlertDialog(
            onDismissRequest = { if (!generating) showGenerate = false },
            title = { Text("生成邀请码") },
            text = {
                Column {
                    Text("邀请码一码一用，仅可用于注册普通账号。", style = MaterialTheme.typography.bodySmall)
                    Spacer(Modifier.height(Space.md))
                    OutlinedTextField(
                        value = genCount,
                        onValueChange = { genCount = it.filter { c -> c.isDigit() }.take(2) },
                        label = { Text("数量（1-50）") },
                        singleLine = true,
                        modifier = Modifier.fillMaxWidth(),
                    )
                    Spacer(Modifier.height(Space.sm))
                    OutlinedTextField(
                        value = genNote,
                        onValueChange = { genNote = it },
                        label = { Text("备注（可选，便于追溯）") },
                        singleLine = true,
                        modifier = Modifier.fillMaxWidth(),
                    )
                    Reveal(lastGenerated.isNotEmpty()) {
                        if (lastGenerated.isNotEmpty()) {
                            Spacer(Modifier.height(Space.md))
                            Text("刚生成：", style = MaterialTheme.typography.labelMedium)
                            lastGenerated.forEach { c ->
                                Row(verticalAlignment = Alignment.CenterVertically) {
                                    Text(c, fontFamily = FontFamily.Monospace, style = MaterialTheme.typography.bodyMedium)
                                    Spacer(Modifier.weight(1f))
                                    TextButton(onClick = {
                                        clipboard.setText(AnnotatedString(c))
                                        scope.launch { snackbar.showSnackbar("已复制") }
                                    }) { Text(stringResource(R.string.action_copy)) }
                                }
                            }
                        }
                    }
                }
            },
            confirmButton = {
                TextButton(
                    onClick = {
                        val n = genCount.toIntOrNull()?.coerceIn(1, 50) ?: 1
                        generating = true
                        scope.launch {
                            val r = withContext(Dispatchers.IO) {
                                runCatching { Api.createInvites(n, genNote.ifBlank { null }) }
                            }
                            generating = false
                            r.onSuccess { resp ->
                                lastGenerated = resp.codes.map { it.code }
                                // 一次就把全部码复制走，方便直接发给人。
                                clipboard.setText(AnnotatedString(lastGenerated.joinToString("\n")))
                                snackbar.showSnackbar("已生成 ${lastGenerated.size} 个并复制")
                                reload()
                            }.onFailure { snackbar.showSnackbar(Api.userMessage(it)) }
                        }
                    },
                    enabled = !generating,
                ) { Text(if (generating) "生成中…" else "生成") }
            },
            dismissButton = { TextButton(onClick = { showGenerate = false; lastGenerated = emptyList() }) { Text(stringResource(R.string.action_close)) } },
        )
    }
}

@Composable
private fun StatsRow(stats: AdminStats) {
    Column(Modifier.padding(horizontal = 12.dp, vertical = 8.dp)) {
        Row(Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(Space.sm)) {
            StatChip("用户", stats.users, Icons.Filled.Person)
            StatChip("机器人", stats.bots, Icons.Filled.SmartToy)
            StatChip(stringResource(R.string.status_online), stats.online, Icons.Filled.Group)
            StatChip("管理员", stats.admins, Icons.Filled.Group)
        }
        Spacer(Modifier.height(6.dp))
        Row(Modifier.fillMaxWidth().horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(Space.sm)) {
            StatChip("会话", stats.conversations, null)
            StatChip("消息", stats.messages, null)
            StatChip("文件", stats.files, null)
            StatChip("设备", stats.devices, null)
        }
    }
}

@Composable
private fun StatChip(label: String, value: Int, icon: androidx.compose.ui.graphics.vector.ImageVector?) {
    Surface(
        color = MaterialTheme.colorScheme.secondaryContainer,
        shape = MaterialTheme.shapes.small,
    ) {
        Row(Modifier.padding(horizontal = 10.dp, vertical = 6.dp), verticalAlignment = Alignment.CenterVertically) {
            if (icon != null) {
                Icon(icon, contentDescription = null, modifier = Modifier.size(14.dp))
                Spacer(Modifier.width(Space.xs))
            }
            Text("$label $value", style = MaterialTheme.typography.labelMedium)
        }
    }
}

@Composable
private fun AdminUserRow(u: AdminUser, modifier: Modifier = Modifier, onClick: () -> Unit) {
    ListItem(
        modifier = modifier
            .fillMaxWidth()
            .padding(horizontal = 10.dp, vertical = 3.dp)
            .motionPress(pressedScale = 0.99f)
            .clip(MaterialTheme.shapes.medium)
            .background(MaterialTheme.colorScheme.surfaceContainer)
            .clickable(onClick = onClick),
        colors = androidx.compose.material3.ListItemDefaults.colors(containerColor = androidx.compose.ui.graphics.Color.Transparent),
        leadingContent = { InitialsAvatar(name = u.displayName, size = 40.dp, isBot = u.isBot, online = u.isOnline) },
        headlineContent = {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Text(u.displayName, fontWeight = FontWeight.Medium, maxLines = 1, overflow = androidx.compose.ui.text.style.TextOverflow.Ellipsis)
                if (u.isAdmin) {
                    Spacer(Modifier.width(6.dp))
                    Surface(color = MaterialTheme.colorScheme.primaryContainer, shape = MaterialTheme.shapes.extraSmall) {
                        Text("管理员", style = MaterialTheme.typography.labelSmall, modifier = Modifier.padding(horizontal = 5.dp, vertical = 1.dp))
                    }
                }
                if (u.isBot) {
                    Spacer(Modifier.width(6.dp))
                    Surface(color = MaterialTheme.colorScheme.tertiaryContainer, shape = MaterialTheme.shapes.extraSmall) {
                        Text("机器人", style = MaterialTheme.typography.labelSmall, modifier = Modifier.padding(horizontal = 5.dp, vertical = 1.dp))
                    }
                }
            }
        },
        supportingContent = {
            Text(
                "@${u.username} · 会话 ${u.conversationCount} · 注册 ${Format.relative(u.createdAt)}",
                style = MaterialTheme.typography.bodySmall,
                maxLines = 1,
            )
        },
        trailingContent = {
            Text(
                if (u.isOnline) stringResource(R.string.status_online) else (u.lastSeen?.let { Format.relative(it) } ?: stringResource(R.string.status_offline)),
                style = MaterialTheme.typography.labelSmall,
                color = MaterialTheme.colorScheme.onSurfaceVariant,
            )
        },
    )
}

@Composable
private fun InviteTab(
    stats: InviteStats,
    invites: List<InviteCode>,
    onGenerate: () -> Unit,
    onCopy: (String) -> Unit,
    onRevoke: (String) -> Unit,
) {
    Column(Modifier.fillMaxSize()) {
        Row(
            Modifier.fillMaxWidth().padding(horizontal = 12.dp, vertical = 8.dp),
            horizontalArrangement = Arrangement.spacedBy(Space.sm),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            StatChip("共", stats.total, null)
            StatChip("未用", stats.unused, null)
            StatChip("已用", stats.used, null)
            Spacer(Modifier.weight(1f))
            Button(onClick = onGenerate) { Text("生成") }
        }
        // 空状态 ↔ 列表 之间淡切。
        FadeSwap(target = invites.isEmpty()) { empty ->
            if (empty) {
                EmptyState(Icons.Filled.CardGiftcard, "还没有邀请码", "点击上方「生成」创建")
            } else {
                LazyColumn(Modifier.fillMaxSize()) {
                    items(invites, key = { it.code }) { inv ->
                        ListItem(
                            modifier = Modifier
                                .animateItem()
                                .fillMaxWidth()
                                .padding(horizontal = 10.dp, vertical = 3.dp)
                                .clip(MaterialTheme.shapes.medium)
                                .background(MaterialTheme.colorScheme.surfaceContainer),
                            colors = androidx.compose.material3.ListItemDefaults.colors(containerColor = androidx.compose.ui.graphics.Color.Transparent),
                            headlineContent = {
                                Text(inv.code, fontFamily = FontFamily.Monospace, fontWeight = FontWeight.Medium)
                            },
                            supportingContent = {
                                Text(
                                    buildString {
                                        append(if (inv.used) "已用" else "未使用")
                                        inv.usedByName?.let { append(" · $it") }
                                        inv.usedAt?.let { append(" · ${Format.relative(it)}") }
                                        append(" · 生成 ${Format.relative(inv.createdAt)}")
                                        inv.createdByName?.let { append(" · by $it") }
                                        inv.note?.takeIf { it.isNotBlank() }?.let { append(" · $it") }
                                    },
                                    style = MaterialTheme.typography.bodySmall,
                                    maxLines = 2,
                                )
                            },
                            trailingContent = {
                                Row {
                                    IconButton(onClick = { onCopy(inv.code) }) {
                                        Icon(Icons.Filled.ContentCopy, stringResource(R.string.action_copy), Modifier.size(18.dp))
                                    }
                                    if (!inv.used) {
                                        IconButton(onClick = { onRevoke(inv.code) }) {
                                            Icon(
                                                Icons.Filled.Delete, "作废", Modifier.size(18.dp),
                                                tint = MaterialTheme.colorScheme.error,
                                            )
                                        }
                                    }
                                }
                            },
                        )
                    }
                }
            }
        }
    }
}

/** 会话列表行：显示成员、消息数、最后活跃时间。 */
@Composable
private fun AdminConversationRow(
    c: com.rtcomm.app.data.AdminConversation,
    modifier: Modifier = Modifier,
    onClick: () -> Unit,
) {
    ListItem(
        modifier = modifier
            .fillMaxWidth()
