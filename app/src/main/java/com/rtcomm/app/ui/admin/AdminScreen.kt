/** 查看某个会话的消息（管理员只读）。 */
@Composable
private fun ConversationViewerDialog(
    conversation: com.rtcomm.app.data.AdminConversation,
    onDismiss: () -> Unit,
) {
    var loading by remember { mutableStateOf(true) }
    var err by remember { mutableStateOf<String?>(null) }
    var messages by remember { mutableStateOf<List<com.rtcomm.app.data.Message>>(emptyList()) }
    var expanded by remember { mutableStateOf(true) }

    LaunchedEffect(conversation.id, expanded) {
        if (!expanded) return@LaunchedEffect
        loading = true
        err = null
        val res = withContext(Dispatchers.IO) {
            runCatching { Api.adminConversationMessages(conversation.id) }
        }
        res.onSuccess { messages = it }
        res.onFailure { err = Api.userMessage(it) }
        loading = false
    }

    AppAlertDialog(
        onDismissRequest = onDismiss,
        title = { Text(conversation.title + "（只读）", maxLines = 1) },
        text = {
            Column(Modifier.heightIn(max = 460.dp)) {
                Box(Modifier.fillMaxWidth().height(3.dp)) {
                    if (loading) LinearProgressIndicator(Modifier.fillMaxWidth().height(3.dp))
                }
                err?.let { Text(it, color = MaterialTheme.colorScheme.error, style = MaterialTheme.typography.bodySmall) }
                // 加载 → 空 → 列表 之间淡切。
                FadeSwap(target = if (loading && messages.isEmpty()) 0 else if (messages.isEmpty()) 1 else 2) { st ->
                    when (st) {
                        0 -> Box(Modifier.fillMaxWidth().padding(vertical = 8.dp))
                        1 -> Text("这个会话还没有消息", style = MaterialTheme.typography.bodySmall)
                        else -> LazyColumn(Modifier.fillMaxWidth()) {
                            items(messages.reversed(), key = { it.id }) { m ->
                                val who = m.sender?.displayName ?: m.senderId.take(6)
                                Text(
                                    "$who： " + when {
                                        m.isDeleted -> "<已撤回>"
                                        m.isFileType -> "[文件] " + (m.file?.fileName ?: "")
                                        else -> Format.mdToPlain(m.content).ifBlank { "[空]" }
                                    },
                                    style = MaterialTheme.typography.bodySmall,
                                    modifier = Modifier.animateItem().fillMaxWidth().padding(vertical = 3.dp),
                                )
                            }
                        }
                    }
                }
                if (messages.size >= 200) {
                    Text(
                        "仅显示最近 200 条",
                        style = MaterialTheme.typography.labelSmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                    )
                }
            }
        },
        confirmButton = { TextButton(onClick = onDismiss) { Text(stringResource(R.string.action_close)) } },
    )
}

/**
 * 全局 AI 提供者默认设置（仅管理员）。
 * API Key 只写不读：服务端仅返回是否已配置，留空表示保持原值。
 */
@OptIn(ExperimentalLayoutApi::class)
@Composable
private fun AiSettingsTab(snackbar: SnackbarHostState) {
    val scope = rememberCoroutineScope()
    var loading by remember { mutableStateOf(true) }
    var err by remember { mutableStateOf<String?>(null) }
    var presets by remember { mutableStateOf<Map<String, com.rtcomm.app.data.ProviderPreset>>(emptyMap()) }
    var saved by remember { mutableStateOf<Map<String, com.rtcomm.app.data.ProviderSettings>>(emptyMap()) }
    var baseUrls by remember { mutableStateOf<Map<String, String>>(emptyMap()) }
    var models by remember { mutableStateOf<Map<String, String>>(emptyMap()) }
    var apiKeys by remember { mutableStateOf<Map<String, String>>(emptyMap()) }
    var busy by remember { mutableStateOf(false) }
    /** 待确认清除 Key 的服务商 id。 */
    var confirmClearKey by remember { mutableStateOf<String?>(null) }

    suspend fun load() {
        loading = true; err = null
        val r = withContext(Dispatchers.IO) { runCatching { Api.providersSettings() } }
        r.onSuccess { res ->
            presets = res.presets
            saved = res.settings
            baseUrls = res.settings.mapValues { it.value.baseUrl.orEmpty() }
            // deepseek 无已保存模型时预填官方可用模型 deepseek-flash。
            models = res.settings.mapValues { (id, s) ->
                s.model.orEmpty().ifBlank {
                    if (id == "deepseek") "deepseek-flash" else res.presets[id]?.model.orEmpty()
                }
            }
        }
        r.onFailure { err = Api.userMessage(it) }
        loading = false
    }
    LaunchedEffect(Unit) { load() }

    val ids = remember(presets, saved) { (presets.keys + saved.keys).toList().sorted() }

    Column(Modifier.fillMaxSize().padding(12.dp)) {
        Text(
            "全局 Key 仅加密存储在服务端、不回显；机器人可在各自配置里单独覆盖。聊天总结优先使用这里配置的 Key。",
            style = MaterialTheme.typography.bodySmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
        Spacer(Modifier.height(Space.sm))
        if (err != null) ErrorBanner(err!!, onRetry = { scope.launch { load() } })
        if (loading) { LinearProgressIndicator(Modifier.fillMaxWidth()); Spacer(Modifier.height(Space.sm)) }

        LazyColumn(Modifier.weight(1f)) {
            items(ids, key = { it }) { id ->
                val preset = presets[id]
                val s = saved[id]
                Card(Modifier.animateItem().fillMaxWidth().padding(vertical = 5.dp)) {
                    Column(Modifier.padding(12.dp)) {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Text(preset?.label ?: id, fontWeight = FontWeight.Medium, modifier = Modifier.weight(1f))
                            val status = when {
                                s?.hasApiKey == true -> "已配置 Key"
                                preset?.needsApiKey == false -> "无需 Key"
                                else -> "未配置 Key"
                            }
                            AssistChip(onClick = {}, label = { Text(status) })
                        }
                        Spacer(Modifier.height(6.dp))
                        OutlinedTextField(
                            value = baseUrls[id].orEmpty(),
                            onValueChange = { baseUrls = baseUrls + (id to it) },
                            label = { Text("baseUrl") },
                            singleLine = true,
                            supportingText = preset?.baseUrl?.let { url -> { Text("默认 $url") } },
                            modifier = Modifier.fillMaxWidth(),
                        )
                        Spacer(Modifier.height(6.dp))
                        OutlinedTextField(
                            value = models[id].orEmpty(),
                            onValueChange = { models = models + (id to it) },
                            label = { Text("model") },
                            singleLine = true,
                            supportingText = preset?.model?.let { m -> { Text("预设 $m") } },
                            modifier = Modifier.fillMaxWidth(),
                        )
                        // 该提供者的常用模型名，点选即填入。
                        val modelList = preset?.models.orEmpty()
                        if (modelList.isNotEmpty()) {
                            FlowRow(horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                                modelList.forEach { m ->
                                    SuggestionChip(
                                        onClick = { models = models + (id to m) },
                                        label = { Text(m) },
                                    )
                                }
                            }
                        }
                        Spacer(Modifier.height(6.dp))
                        OutlinedTextField(
                            value = apiKeys[id].orEmpty(),
                            onValueChange = { apiKeys = apiKeys + (id to it) },
                            label = { Text(if (s?.hasApiKey == true) "API Key（留空保持不变）" else "API Key") },
                            singleLine = true,
                            visualTransformation = PasswordVisualTransformation(),
                            keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Password),
                            modifier = Modifier.fillMaxWidth(),
                        )
                        if (s?.hasApiKey == true) {
                            Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.End) {
                                TextButton(onClick = { confirmClearKey = id }) {
                                    Text("清除 Key", color = MaterialTheme.colorScheme.error)
                                }
                            }
                        }
                    }
                }
            }
        }

        Spacer(Modifier.height(Space.sm))
        Button(
            enabled = !busy && !loading,
            onClick = {
                busy = true
                scope.launch {
                    val body = mutableMapOf<String, Any?>()
                    for (id in ids) {
                        val part = mutableMapOf<String, Any?>(
                            "baseUrl" to baseUrls[id].orEmpty().trim(),
                            "model" to models[id].orEmpty().trim(),
                        )
                        val key = apiKeys[id].orEmpty()
                        if (key.isNotBlank()) part["apiKey"] = key
                        body[id] = part
                    }
                    val r = withContext(Dispatchers.IO) { runCatching { Api.updateProvidersSettings(body) } }
                    busy = false
                    r.onSuccess { apiKeys = emptyMap(); snackbar.showSnackbar("全局 AI 设置已保存"); load() }
                        .onFailure { err = Api.userMessage(it); snackbar.showSnackbar(Api.userMessage(it)) }
                }
            },
            modifier = Modifier.fillMaxWidth(),
        ) { Text(if (busy) "保存中…" else "保存全局设置") }

        confirmClearKey?.let { id ->
            ConfirmDialog(
                title = "清除 API Key",
                message = "将清除「${id}」在服务端保存的全局 API Key，使用该 Key 的机器人/总结会立即失效。",
                confirmText = "清除",
                onConfirm = {
                    scope.launch {
                        val r = withContext(Dispatchers.IO) {
                            runCatching { Api.updateProvidersSettings(mapOf(id to mapOf("apiKey" to ""))) }
                        }
                        r.onSuccess { snackbar.showSnackbar("已清除 $id 的 Key"); load() }
                            .onFailure { snackbar.showSnackbar(Api.userMessage(it)) }
                    }
                },
                onDismiss = { confirmClearKey = null },
            )
        }
    }
}

/**
 * 额度兑换码管理（仅管理员）：自定义额度与有效期，生成/复制/作废。
 */
@OptIn(ExperimentalMaterial3Api::class, ExperimentalLayoutApi::class)
@Composable
private fun RedeemCodesTab(
    snackbar: SnackbarHostState,
    clipboard: androidx.compose.ui.platform.ClipboardManager,
) {
    val scope = rememberCoroutineScope()
    var tokens by remember { mutableStateOf("10000") }
    var count by remember { mutableStateOf("1") }
    var days by remember { mutableStateOf("0") }
    var note by remember { mutableStateOf("") }
    var busy by remember { mutableStateOf(false) }
    var err by remember { mutableStateOf<String?>(null) }
    var codes by remember { mutableStateOf<List<com.rtcomm.app.data.RedeemCode>>(emptyList()) }
    var loading by remember { mutableStateOf(true) }
    var lastCreated by rememberSaveable(stateSaver = StringListSaver) { mutableStateOf<List<String>>(emptyList()) }
    /** 待确认作废的兑换码。 */
    var confirmRevoke by remember { mutableStateOf<String?>(null) }

    suspend fun load() {
        loading = true
        val r = withContext(Dispatchers.IO) { runCatching { Api.redeemCodes() } }
        r.onSuccess { codes = it }
        r.onFailure { err = Api.userMessage(it) }
        loading = false
    }
    LaunchedEffect(Unit) { load() }

    Column(Modifier.fillMaxSize().padding(12.dp)) {
        Text("发放额度兑换码", style = MaterialTheme.typography.titleSmall)
        Spacer(Modifier.height(Space.sm))
        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(Space.sm)) {
            OutlinedTextField(
                tokens, { tokens = it }, label = { Text("额度(tokens)") }, singleLine = true,
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number), modifier = Modifier.weight(1f),
            )
            OutlinedTextField(
                count, { count = it }, label = { Text("数量") }, singleLine = true,
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number), modifier = Modifier.width(96.dp),
            )
        }
        Spacer(Modifier.height(6.dp))
        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.spacedBy(Space.sm)) {
            OutlinedTextField(
                days, { days = it }, label = { Text("有效期(天, 0=永久)") }, singleLine = true,
                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Number), modifier = Modifier.weight(1f),
            )
            OutlinedTextField(note, { note = it }, label = { Text("备注(可选)") }, singleLine = true, modifier = Modifier.weight(1f))
        }
        Spacer(Modifier.height(Space.sm))
        Button(
            enabled = !busy,
            onClick = {
                val t = tokens.trim().toIntOrNull() ?: 0
                val c = count.trim().toIntOrNull() ?: 1
                val d = days.trim().toIntOrNull() ?: 0
                if (t <= 0) { err = "额度必须为正整数"; return@Button }
                busy = true; err = null
                scope.launch {
                    val expiresAt = if (d > 0) {
                        java.time.Instant.now().plus(d.toLong(), java.time.temporal.ChronoUnit.DAYS).toString()
                    } else null
                    val r = withContext(Dispatchers.IO) {
                        runCatching { Api.createRedeemCodes(t, c, expiresAt, note.ifBlank { null }) }
                    }
                    busy = false
                    r.onSuccess { res ->
                        lastCreated = res.codes
                        snackbar.showSnackbar("已生成 ${res.codes.size} 个兑换码")
                        load()
                    }
                    r.onFailure { err = Api.userMessage(it) }
                }
            },
            modifier = Modifier.fillMaxWidth(),
        ) { Text(if (busy) "生成中…" else "生成兑换码") }
        err?.let { Spacer(Modifier.height(6.dp)); Text(it, color = MaterialTheme.colorScheme.error, style = MaterialTheme.typography.bodySmall) }

        Reveal(lastCreated.isNotEmpty()) {
            if (lastCreated.isNotEmpty()) {
                Spacer(Modifier.height(Space.sm))
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(12.dp)) {
                        Text("刚刚生成", style = MaterialTheme.typography.labelMedium)
                        lastCreated.forEach { code ->
                            Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
                                Text(code, fontFamily = FontFamily.Monospace, modifier = Modifier.weight(1f))
                                IconButton(onClick = {
                                    clipboard.setText(AnnotatedString(code))
                                    scope.launch { snackbar.showSnackbar("已复制") }
                                }) { Icon(Icons.Filled.ContentCopy, contentDescription = stringResource(R.string.action_copy)) }
                            }
                        }
                    }
                }
            }
        }

        Spacer(Modifier.height(10.dp))
        Text("历史兑换码", style = MaterialTheme.typography.titleSmall)
        if (loading) LinearProgressIndicator(Modifier.fillMaxWidth())
        LazyColumn(Modifier.weight(1f)) {
            items(codes, key = { it.code }) { c ->
                Card(Modifier.animateItem().fillMaxWidth().padding(vertical = 4.dp)) {
                    Column(Modifier.padding(10.dp)) {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Text(c.code, fontFamily = FontFamily.Monospace, modifier = Modifier.weight(1f))
                            IconButton(onClick = {
                                clipboard.setText(AnnotatedString(c.code))
                                scope.launch { snackbar.showSnackbar("已复制") }
                            }) { Icon(Icons.Filled.ContentCopy, contentDescription = stringResource(R.string.action_copy)) }
                        }
                        Text(
                            buildString {
                                append("${c.tokens} tokens · ")
                                append(if (c.expiresAt != null) "有效期至 ${c.expiresAt}" else "永久")
                                append(if (c.usedBy != null) " · 已使用" else " · 未使用")
                            },
                            style = MaterialTheme.typography.labelSmall,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                        c.note?.takeIf { it.isNotBlank() }?.let { Text(it, style = MaterialTheme.typography.labelSmall) }
                        if (c.usedBy == null) {
                            TextButton(onClick = { confirmRevoke = c.code }) {
                                Text("作废", color = MaterialTheme.colorScheme.error)
                            }
                        }
                    }
                }
            }
        }

        confirmRevoke?.let { code ->
            ConfirmDialog(
                title = "作废兑换码",
                message = "作废后「$code」将无法再被兑换，此操作不可撤销。",
                confirmText = "作废",
                onConfirm = {
                    scope.launch {
                        val r = withContext(Dispatchers.IO) { runCatching { Api.revokeRedeemCode(code) } }
                        r.onSuccess { snackbar.showSnackbar("已作废"); load() }
                            .onFailure { snackbar.showSnackbar(Api.userMessage(it)) }
                    }
                },
                onDismiss = { confirmRevoke = null },
            )
        }
    }
}
